#!/usr/bin/env bash
# Regenerates SCREENSHOTS.md from {/* SCREENSHOT: ... */} markers in the .mdx pages.
cd "$(dirname "$0")/.."
{
  echo "# Screenshot shot list"
  echo
  echo "Generated by \`scripts/screenshot-list.sh\`. Save each image at the path shown (PNG, light mode, ~1600px wide),"
  echo "then replace the marker in the page with:"
  echo
  echo '```mdx'
  echo '<Frame><img src="/images/section/name.png" alt="Short description" /></Frame>'
  echo '```'
  echo
  grep -rn --include='*.mdx' 'SCREENSHOT:' . | sed -E 's#^\./##' | while IFS= read -r line; do
    file=${line%%:*}; rest=${line#*:}; ln=${rest%%:*}; body=${rest#*:}
    body=$(echo "$body" | sed -E 's#.*SCREENSHOT:[[:space:]]*##; s#[[:space:]]*\*/\}.*$##')
    path=${body%% |*}; desc=${body#*| }
    status="[ ]"; [ -f "${path#/}" ] && status="[x]"
    echo "- $status \`$path\` — $desc  _($file:$ln)_"
  done
} > SCREENSHOTS.md
echo "Wrote SCREENSHOTS.md ($(grep -c '^- \[' SCREENSHOTS.md) shots)"
